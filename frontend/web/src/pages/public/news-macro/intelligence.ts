export function eventInterpretation(
  title: string,
  actual: number | null,
  forecast: number | null,
) {
  const text = title.toLowerCase();
  let meaning =
    "Публикация добавляет новую информацию об экономике. Её влияние зависит от ожиданий рынка, деталей отчёта и текущих условий.";
  let upside =
    "Более благоприятные для роста и ликвидности данные могут поддержать BTC, ETH и фондовые индексы.";
  let downside =
    "Усиление экономических рисков может увеличить волатильность. Доллар и рискованные активы могут реагировать по-разному.";
  if (/cpi|pce|price|inflation|инфляц/.test(text)) {
    meaning =
      "Показатель описывает давление цен. ФРС учитывает инфляцию при выборе ставки; рынки переоценивают будущую стоимость денег.";
    upside =
      "Инфляция ниже ожиданий может усилить ожидания снижения ставки: это иногда поддерживает BTC, ETH и акции и ослабляет доллар.";
    downside =
      "Инфляция выше ожиданий может усилить ожидания жёсткой политики: доходности и доллар иногда растут, а рискованные активы испытывают давление.";
  } else if (/fomc|interest|rate decision|ставк|federal reserve/.test(text)) {
    meaning =
      "Решение центрального банка влияет на стоимость кредитования и ожидания ликвидности. Формулировки заявления могут быть важнее самого изменения ставки.";
    upside =
      "Более мягкая политика относительно ожиданий может поддержать рискованные активы и снизить доходности облигаций.";
    downside =
      "Более жёсткая политика относительно ожиданий может поддержать доллар и увеличить давление на BTC, ETH и акции.";
  } else if (/employment|payroll|unemployment|job|труд|занят/.test(text)) {
    meaning =
      "Отчёт помогает оценить силу рынка труда. Занятость, зарплаты и участие в рабочей силе стоит рассматривать вместе.";
    upside =
      "Умеренное охлаждение труда иногда снижает ожидания ставки и поддерживает рискованные активы при сохранении устойчивой экономики.";
    downside =
      "Слишком слабые данные могут усилить страх рецессии; слишком сильные — отложить ожидаемое смягчение политики.";
  }
  const surprise =
    actual != null && forecast != null ? actual - forecast : null;
  return {
    meaning,
    scenarios: [upside, downside],
    surprise,
    caveat:
      "Условные сценарии, а не прогноз. Реакция зависит от того, что уже учтено в цене; совпадение во времени не доказывает причинность.",
  };
}
