// Run after backtest-indicators-live.mjs against the locally built stack.
// All jobs are real; only the chart chunk failure is deliberately injected.
import { chromium, expect } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import path from "node:path";
import { defaultRequest } from "../src/pages/public/backtest/model.ts";
import { makeRule } from "../src/pages/public/backtest/rules.ts";

const root = path.resolve("../.."), out = path.join(root, "docs/backtest/indicators");
const evidence = JSON.parse(readFileSync(path.join(out, "checks.json"), "utf8"));
const prior = evidence.jobs.find((job) => job.label === "UI price");
const lines = readFileSync(path.join(root, "README.md"), "utf8").split(/\r?\n/);
const login = lines.findIndex((line) => line.trim() === "admin@local.dev");
if (login < 0 || !prior) throw Error("Run the main local QA first");
const browser = await chromium.launch({ channel: "msedge", headless: true });
const checks = []; const pass = (name) => { checks.push(name); console.log("PASS", name); };
let context, activeId;
try {
  context = await browser.newContext({ viewport: { width: 1536, height: 1050 } });
  await context.addInitScript(() => { localStorage.setItem("cookie_consent", "essential"); localStorage.setItem("mobile_notice_shown_v1", "1"); });
  const page = await context.newPage();
  await page.goto("http://localhost:3000/login");
  await page.locator("input[type=email]").fill(lines[login].trim());
  await page.locator("input[type=password]").fill(lines[login + 1].trim());
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await page.getByRole("link", { name: "Тест стратегии", exact: true }).waitFor();
  const button = (name) => page.getByRole("button", { name, exact: true });
  await page.route("**/EquityChart-*.js", (route) => route.abort());
  await page.goto(`http://localhost:3000/backtest?job=${prior.id}`);
  await expect(page.getByRole("alert")).toContainText("Не удалось загрузить график");
  await expect(page.locator(".bt-metrics")).toBeVisible();
  await expect(page.locator(".bt-trades tbody tr").first()).toContainText("ADAUSDT");
  await page.unroute("**/EquityChart-*.js"); await button("Обновить страницу").click();
  await expect(page.locator(".bt-equity-chart canvas").first()).toBeVisible();
  await page.locator(".bt-results").evaluate((el) => window.scrollTo(0, el.getBoundingClientRect().top + window.scrollY - 96));
  await page.waitForTimeout(600); await page.screenshot({ path: path.join(out, "results-desktop.png") });
  pass("chart chunk failure keeps metrics/trades; reload restores chart");
  await button("Сбросить настройки").click();
  await page.getByLabel("Начальный капитал, USDT", { exact: true }).fill("");
  await button("Экспорт JSON").click(); await expect(page.getByRole("alert")).toContainText("Перед экспортом");
  await button("Сбросить настройки").click();
  const dropdown = page.getByLabel("Вход в позицию 1: индикатор", { exact: true });
  await dropdown.scrollIntoViewIfNeeded(); await page.waitForTimeout(500);
  await dropdown.focus(); await page.keyboard.press("ArrowDown");
  await page.keyboard.press("End"); await page.keyboard.press("Enter");
  await expect(dropdown).toContainText("Волатильность");
  await dropdown.click(); await page.keyboard.press("Home"); await page.keyboard.press("Enter");
  await expect(dropdown).toContainText("Цена");
  await page.getByLabel("Вход в позицию 1: порог", { exact: true }).fill("3");
  await page.waitForTimeout(600); await page.reload();
  await expect(page.getByLabel("Вход в позицию 1: порог", { exact: true })).toHaveValue("3");
  pass("reset, invalid export, keyboard menu, draft restoration");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await button("Добавить условие").click(); await expect(page.locator(".bt-rule")).toHaveCount(2);
  await button("Удалить вход в позицию 2").click(); await expect(page.locator(".bt-rule")).toHaveCount(1);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(out, "page-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel("Открыть навигацию").click();
  await expect(page.getByRole("navigation", { name: "Мобильная навигация" }).getByRole("link", { name: "Тест стратегии" })).toBeVisible();
  await page.getByRole("navigation", { name: "Мобильная навигация" }).getByRole("link", { name: "Тест стратегии" }).click();
  pass("reduced motion and mobile header navigation");
  const payload = defaultRequest(); payload.symbols = ["ADAUSDT"];
  const to = new Date(); to.setUTCHours(0, 0, 0, 0); to.setUTCDate(to.getUTCDate() - 1);
  payload.to = to.toISOString(); payload.from = new Date(+to - 3 * 86400000).toISOString();
  payload.strategy.entry.children = [{ ...makeRule(), threshold: 1000000 }];
  const created = await context.request.post("http://localhost:3000/api/backtests", { data: { ...payload, requestKey: randomUUID() } });
  expect(created.status()).toBe(202); activeId = (await created.json()).jobId;
  await page.goto(`http://localhost:3000/backtest?job=${activeId}`);
  await expect(page.getByRole("heading", { name: "Результаты теста", exact: true })).toBeVisible({ timeout: 60000 });
  await expect(page.locator(".bt-no-trades")).toContainText("сделок нет");
  await expect(page.locator(".bt-metrics")).not.toContainText(/NaN|undefined/);
  pass("zero signals and trades render without invalid metrics");
  const zeroJob = activeId; activeId = undefined;
  writeFileSync(path.join(out, "resilience-checks.json"), JSON.stringify({ checkedAt: new Date().toISOString(), checks, zeroJob }, null, 2));
} finally {
  if (activeId && context) await context.request.post(`http://localhost:3000/api/backtests/${activeId}/cancel`, { data: {} }).catch(() => {});
  await browser.close();
}
